<script>
document.addEventListener("DOMContentLoaded", function () {

    const carousels = document.querySelectorAll(".law-firm-carousel");

    carousels.forEach(function (carousel) {

        const track = carousel.querySelector(".law-firm-carousel-track");
        const items = carousel.querySelectorAll(".law-firm-carousel-item");

        const prevButton = carousel.querySelector(".law-firm-carousel-prev");
        const nextButton = carousel.querySelector(".law-firm-carousel-next");

        if (!track || !items.length) {
            return;
        }


        let currentIndex = 0;


        /*
        ========================================================
        Get number of visible cards
        ========================================================
        */

        function getVisibleItems() {

            if (window.innerWidth <= 767) {
                return 1;
            }

            if (window.innerWidth <= 991) {
                return 2;
            }

            return 3;
        }


        /*
        ========================================================
        Get maximum slide index
        ========================================================
        */

        function getMaxIndex() {

            const visibleItems = getVisibleItems();

            return Math.max(
                0,
                items.length - visibleItems
            );
        }


        /*
        ========================================================
        Update Carousel
        ========================================================
        */

        function updateCarousel() {

            const visibleItems = getVisibleItems();

            const itemWidth = 100 / visibleItems;

            track.style.transform =
                "translateX(-" +
                (currentIndex * itemWidth) +
                "%)";


            /*
            Disable Previous
            */

            if (currentIndex <= 0) {

                prevButton.disabled = true;

            } else {

                prevButton.disabled = false;

            }


            /*
            Disable Next
            */

            if (currentIndex >= getMaxIndex()) {

                nextButton.disabled = true;

            } else {

                nextButton.disabled = false;

            }

        }


        /*
        ========================================================
        NEXT
        ========================================================
        */

        nextButton.addEventListener("click", function () {

            const maxIndex = getMaxIndex();

            if (currentIndex < maxIndex) {

                currentIndex++;

                updateCarousel();

            }

        });


        /*
        ========================================================
        PREVIOUS
        ========================================================
        */

        prevButton.addEventListener("click", function () {

            if (currentIndex > 0) {

                currentIndex--;

                updateCarousel();

            }

        });


        /*
        ========================================================
        Responsive Resize
        ========================================================
        */

        window.addEventListener("resize", function () {

            const maxIndex = getMaxIndex();

            if (currentIndex > maxIndex) {

                currentIndex = maxIndex;

            }

            updateCarousel();

        });


        /*
        ========================================================
        Initial
        ========================================================
        */

        updateCarousel();

    });

});
</script>